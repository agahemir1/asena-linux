//! Session language: written to the user's systemd environment, which the
//! Asena session services and launched applications read from the next login.
use gio::prelude::*;
use std::path::PathBuf;

fn path() -> PathBuf {
    glib::user_config_dir().join("environment.d/90-asena-language.conf")
}

/// Locale names such as `tr_TR.UTF-8`; anything else is rejected.
pub fn render(language: &str) -> Option<String> {
    let environment = asena_core::i18n::language_environment(language, false);
    if environment.is_empty() {
        return None;
    }
    let mut text = String::from("# Generated by asena-daemon from Asena settings.\n");
    for (name, value) in environment {
        text.push_str(&format!("{name}={value}\n"));
    }
    Some(text)
}

fn apply(language: String) {
    glib::spawn_future_local(async move {
        let result = gio::spawn_blocking(move || -> std::io::Result<()> {
            let path = path();
            match render(&language) {
                Some(contents) => {
                    if let Some(parent) = path.parent() {
                        std::fs::create_dir_all(parent)?;
                    }
                    let temporary = path.with_extension("conf.tmp");
                    std::fs::write(&temporary, contents)?;
                    std::fs::rename(temporary, path)
                }
                None => match std::fs::remove_file(path) {
                    Err(error) if error.kind() != std::io::ErrorKind::NotFound => Err(error),
                    _ => Ok(()),
                },
            }
        })
        .await;
        if let Ok(Err(error)) = result {
            tracing::warn!(%error, "Could not save the session language");
        }
    });
}

pub fn watch(settings: &gio::Settings) {
    // The nested development session must not change the real user's login.
    if std::env::var_os("ASENA_DEV").is_some() {
        return;
    }
    apply(settings.string("language").to_string());
    settings.connect_changed(Some("language"), |settings, _| {
        apply(settings.string("language").to_string());
    });
}

#[cfg(test)]
mod tests {
    use super::render;

    #[test]
    fn only_locale_names_are_written() {
        assert_eq!(
            render("tr_TR.UTF-8").as_deref(),
            Some(
                "# Generated by asena-daemon from Asena settings.\nLANG=tr_TR.UTF-8\nLANGUAGE=tr_TR:tr\nLC_MESSAGES=tr_TR.UTF-8\n"
            )
        );
        assert!(render("").is_none());
        assert!(render("tr_TR.UTF-8\nPATH=/tmp").is_none());
        assert!(render("en US").is_none());
    }
}
