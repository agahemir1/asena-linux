"""Create a local, short-lived, signed Asena test archive with AppStream data."""
import argparse
import bz2
import gzip
import hashlib
import json
import lzma
import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SUITE = "asena-test"


def run(*args, env=None, stdout=None):
    return subprocess.run(args, check=True, env=env, stdout=stdout)


def release_bytes(directory):
    original = (directory / "Release").read_text()
    headers = []
    for line in original.splitlines():
        if line in {"MD5Sum:", "SHA1:", "SHA256:", "SHA512:"}:
            break
        headers.append(line)
    files = [path for path in sorted(directory.rglob("*")) if path.is_file()
             and path.name not in {"Release.gpg", "InRelease"}
             and path != directory / "Release" and not path.name.endswith(".tmp")]
    output = "\n".join(headers) + "\n"
    for name, algorithm in (("SHA256", "sha256"), ("SHA512", "sha512")):
        output += name + ":\n"
        for path in files:
            with path.open("rb") as stream:
                digest = hashlib.file_digest(stream, algorithm).hexdigest()
            output += f" {digest} {path.stat().st_size:16d} {path.relative_to(directory).as_posix()}\n"
    return output.encode()


def expand_indexes(directory):
    """APT needs the canonical uncompressed index checksum as well."""
    formats = {".gz": gzip.decompress, ".xz": lzma.decompress, ".bz2": bz2.decompress}
    expanded = {}
    for path in sorted(directory.rglob("*")):
        if not path.is_file() or path.suffix not in formats:
            continue
        target = path.with_suffix("")
        data = formats[path.suffix](path.read_bytes())
        if target in expanded and expanded[target] != data:
            raise ValueError(f"Compressed index variants disagree: {target}")
        expanded[target] = data
    for target, data in expanded.items():
        target.write_bytes(data)


def trust_packages(output, fingerprint, public_key, uri):
    if not (uri.startswith("file:/") or uri.startswith("http://127.0.0.1:") or uri.startswith("http://localhost:")):
        raise ValueError("This test trust package only accepts a local file or loopback URI")
    output.mkdir(parents=True, exist_ok=True)
    packages = {
        "asena-test-archive-keyring": {
            "usr/share/keyrings/asena-test-archive-keyring.asc": public_key,
        },
        "asena-test-sources": {
            "etc/apt/sources.list.d/asena-test.sources": (
                f"Types: deb deb-src\nURIs: {uri}\nSuites: {SUITE}\nComponents: main\n"
                "Signed-By: /usr/share/keyrings/asena-test-archive-keyring.asc\n"
            ).encode(),
        },
    }
    epoch = int(subprocess.check_output([
        "dpkg-parsechangelog", "-l", str(ROOT / "packaging/debian/changelog"), "-STimestamp",
    ]))
    env = {**os.environ, "SOURCE_DATE_EPOCH": str(epoch)}
    source = output / "asena-test-trust-0.1.0"
    (source / "debian/source").mkdir(parents=True, exist_ok=True)
    (source / "debian/source/format").write_text("3.0 (native)\n")
    (source / "debian/rules").write_text("#!/usr/bin/make -f\n%:\n\tdh $@\n")
    (source / "debian/rules").chmod(0o755)
    (source / "debian/copyright").write_text(
        "Copyright 2026 Asena Linux contributors\nLicense: GPL-3.0-or-later\n"
        "The public archive key and local APT configuration are generated by\n"
        "scripts/create-apt-test-repo.py in the Asena source package.\n"
    )
    changelog = (ROOT / "packaging/debian/changelog").read_text()
    date = changelog.rsplit("  ", 1)[1].strip()
    (source / "debian/changelog").write_text(
        "asena-test-trust (0.1.0) asena-test; urgency=medium\n\n"
        "  * Generate local acceptance test trust configuration.\n\n"
        f" -- agahemir1 <projectxurme@gmail.com>  {date}\n"
    )
    source_control = (
        "Source: asena-test-trust\nSection: misc\nPriority: optional\n"
        "Maintainer: agahemir1 <projectxurme@gmail.com>\n"
        "Build-Depends: debhelper-compat (= 13)\nStandards-Version: 4.7.2\nRules-Requires-Root: no\n"
    )
    for name, files in packages.items():
        directory = output / name
        directory.mkdir(exist_ok=True)
        control = directory / "DEBIAN/control"
        control.parent.mkdir(exist_ok=True)
        depends = "Depends: asena-test-archive-keyring\n" if name == "asena-test-sources" else ""
        control.write_text(
            f"Package: {name}\nSource: asena-test-trust\nVersion: 0.1.0\nArchitecture: all\nSection: misc\nPriority: optional\n"
            "Maintainer: agahemir1 <projectxurme@gmail.com>\n" + depends +
            f"Description: Local Asena acceptance test trust configuration\n Signing fingerprint: {fingerprint}\n"
        )
        for path, data in files.items():
            target = directory / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            target.chmod(0o644)
            source_file = source / "files" / name / path
            source_file.parent.mkdir(parents=True, exist_ok=True)
            source_file.write_bytes(data)
        sums = "".join(f"{hashlib.md5(data, usedforsecurity=False).hexdigest()}  {path}\n" for path, data in files.items())
        (directory / "DEBIAN/md5sums").write_text(sums)
        conffiles = ["/" + path for path in files if path.startswith("etc/")]
        if conffiles:
            (directory / "DEBIAN/conffiles").write_text("\n".join(conffiles) + "\n")
        for path in [directory, *directory.rglob("*")]:
            os.utime(path, (epoch, epoch))
        run("dpkg-deb", "--root-owner-group", "--build", str(directory), str(output / (name + "_0.1.0_all.deb")), env=env)
        source_control += (
            f"\nPackage: {name}\nArchitecture: all\nDepends: ${{misc:Depends}}"
            + (", asena-test-archive-keyring" if name == "asena-test-sources" else "")
            + "\nDescription: Local Asena acceptance test trust configuration\n"
            + f" Signing fingerprint: {fingerprint}\n"
        )
        (source / "debian" / (name + ".install")).write_text(f"files/{name}/* .\n")
    (source / "debian/control").write_text(source_control)
    for path in [source, *source.rglob("*")]:
        os.utime(path, (epoch, epoch))
    subprocess.run(["dpkg-source", "--build", str(source)], cwd=output, env=env, check=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--packages", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--uri", default="file:/opt/asena-repo")
    args = parser.parse_args()
    output = args.output.resolve()
    keyhome = ROOT / "target/keys/asena-test"
    if keyhome.resolve().is_relative_to(output) or output.is_relative_to(keyhome.resolve()):
        raise ValueError("Private key home and public archive must be separate")
    keyhome.mkdir(parents=True, exist_ok=True, mode=0o700)
    keyhome.chmod(0o700)
    env = {**os.environ, "GNUPGHOME": str(keyhome)}
    if not (keyhome / "asena-test.fingerprint").exists():
        run("gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "",
            "--quick-generate-key", "Asena local test archive", "ed25519", "sign", "7d", env=env)
        keys = subprocess.check_output(["gpg", "--with-colons", "--list-secret-keys"], env=env).decode()
        fingerprint = next(line.split(":")[9] for line in keys.splitlines() if line.startswith("fpr:"))
        (keyhome / "asena-test.fingerprint").write_text(fingerprint + "\n")
    fingerprint = (keyhome / "asena-test.fingerprint").read_text().strip()
    public_key = subprocess.check_output(["gpg", "--armor", "--export", fingerprint], env=env)
    conf = output / "conf"
    conf.mkdir(parents=True, exist_ok=True)
    (conf / "distributions").write_text(
        f"Origin: asena\nLabel: Asena local test archive\nCodename: {SUITE}\nSuite: {SUITE}\n"
        "Architectures: amd64 source\nComponents: main\nDescription: Local Asena acceptance test archive\n"
        f"SignWith: {fingerprint}\nValidFor: 7d\n"
    )
    source_packages = sorted(args.packages.glob("*.dsc"))
    binaries = sorted(args.packages.glob("*.deb"))
    if not source_packages or not binaries:
        raise ValueError("Expected complete source packages and Debian binaries")
    for path in source_packages:
        run("reprepro", "--export=never", "--keepunreferencedfiles", "-b", str(output), "includedsc", SUITE, str(path.resolve()), env=env)
    for path in binaries:
        run("reprepro", "--export=never", "--keepunreferencedfiles", "-b", str(output), "includedeb", SUITE, str(path.resolve()), env=env)
    trust = output.parent / (output.name + "-trust")
    trust_packages(trust, fingerprint, public_key, args.uri)
    for path in sorted(trust.glob("*.dsc")):
        run("reprepro", "--export=never", "--keepunreferencedfiles", "-b", str(output), "includedsc", SUITE, str(path), env=env)
    for path in sorted(trust.glob("*.deb")):
        run("reprepro", "--export=never", "--keepunreferencedfiles", "-b", str(output), "includedeb", SUITE, str(path), env=env)
    run("reprepro", "-b", str(output), "export", SUITE, env=env)
    workspace = output.parent / (output.name + "-catalog")
    workspace.mkdir(exist_ok=True)
    config = {
        "ProjectName": "asena", "ArchiveRoot": str(output), "Backend": "debian",
        "MediaBaseUrl": "http://127.0.0.1/asena-test-media", "MetadataType": "YAML", "ImageFormat": "png",
        "Suites": {SUITE: {"sections": ["main"], "architectures": ["amd64"], "useIconTheme": "Asena"}},
        "Features": {"noDownloads": True, "processDesktop": False, "processFonts": False, "processGStreamer": False,
                     "optimizePNGSize": False, "metadataTimestamps": False, "screenshotVideos": False},
        "Icons": {"64x64": {"cached": True, "remote": False}, "128x128": {"cached": True, "remote": False}},
    }
    (workspace / "asgen-config.json").write_text(json.dumps(config, indent=2))
    run("appstream-generator", "--workspace", str(workspace), "run", SUITE)
    catalog = workspace / "export/data" / SUITE / "main"
    if not list(catalog.glob("Components-amd64.yml*")):
        raise ValueError(f"No generated AppStream catalog in {catalog}")
    target = output / "dists" / SUITE / "main/dep11"
    target.mkdir(parents=True, exist_ok=True)
    for path in catalog.iterdir():
        if path.is_file():
            shutil.copyfile(path, target / path.name)
    release = output / "dists" / SUITE / "Release"
    expand_indexes(release.parent)
    release.write_bytes(release_bytes(release.parent))
    run("gpg", "--batch", "--yes", "--local-user", fingerprint, "--digest-algo", "SHA512",
        "--clearsign", "--output", str(release.with_name("InRelease.tmp")), str(release), env=env)
    run("gpg", "--batch", "--yes", "--local-user", fingerprint, "--armor", "--detach-sign",
        "--output", str(release.with_name("Release.gpg.tmp")), str(release), env=env)
    release.with_name("InRelease.tmp").replace(release.with_name("InRelease"))
    release.with_name("Release.gpg.tmp").replace(release.with_name("Release.gpg"))
    (output / "asena-test-archive-keyring.asc").write_bytes(public_key)
    (output / "TEST-ARCHIVE.txt").write_text(
        f"Local acceptance test only. Suite: {SUITE}. Key: {fingerprint}. Validity: seven days.\n"
        "This archive is not the public Asena update service. Never publish the private key directory.\n"
    )
    print(f"Local signed test archive: {output}\nFingerprint: {fingerprint}")


if __name__ == "__main__":
    main()
