#!/bin/bash
set -euo pipefail
[[ $(uname -s) == Linux ]] || { printf '%s\n' 'Linux is required.' >&2; exit 1; }
repo=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
mkdir -p "$repo/target/schemas"
cp "$repo"/data/schemas/*.gschema.xml "$repo/target/schemas/"
glib-compile-schemas --strict "$repo/target/schemas"
while IFS= read -r language; do
    [[ -n $language && $language != \#* ]] || continue
    mkdir -p "$repo/target/locale/$language/LC_MESSAGES"
    msgfmt --check --check-header -o "$repo/target/locale/$language/LC_MESSAGES/asena.mo" \
        "$repo/po/$language.po"
done < "$repo/po/LINGUAS"
# Asena line icon theme and application icons; generated by scripts/icons/*.py.
mkdir -p "$repo/target/share/icons"
rm -rf "$repo/target/share/icons/Asena" "$repo/target/share/icons/Asena-"* "$repo/target/share/icons/hicolor"
# Asena-<accent> themes hold the accent-colored folders; see scripts/icons/apps.py.
cp -r "$repo/data/icons/Asena" "$repo/data/icons/Asena-"* "$repo/data/icons/hicolor" "$repo/target/share/icons/"
# XDG_CURRENT_DESKTOP=Asena selects asena-portals.conf from XDG_DATA_DIRS.
mkdir -p "$repo/target/share/xdg-desktop-portal"
cp "$repo/data/portals/asena-portals.conf" "$repo/target/share/xdg-desktop-portal/"
mkdir -p "$repo/target/share/xdg-desktop-portal/portals"
cp "$repo/data/portals/asena.portal" "$repo/target/share/xdg-desktop-portal/portals/"
mkdir -p "$repo/target/share/applications"
cp "$repo"/data/applications/*.desktop "$repo/target/share/applications/"
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$repo/target/share/applications" 2>/dev/null || true
fi
# Keep Turkish test locale data local; do not change the system's default locale.
mkdir -p "$repo/target/locale-data"
localedef --no-archive -i tr_TR -f UTF-8 "$repo/target/locale-data/tr_TR.utf8"
